// Variable called score with a value between 0 & 100
let score = 85;

// Variable called passingGrade set at 60
let passingGrade = 60;

// Print "Passed" or "Failed" based on the score
// if statement to check if score is greater than or equal to passingGrade
if (score >= passingGrade) {
  console.log("You passed!");

  // Else statement for when the score is below passingGrade
} else {
  console.log("You failed.");
}

// Condition to check if the score is perfect (100)
if (score === 100) {
  console.log("You got a perfect score!");
}
