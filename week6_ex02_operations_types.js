// Variable called number1 with a number stored in it
let number1 = 10;

// Variable called number2 with a different number stored in it
let number2 = 5;

// Convert number1 to a string & store it in a variable called stringNumber1
let stringNumber1 = number1.toString();

// Add number1 and number2 together and store the result in a variable called sum
let sum = number1 + number2;

// Multiply number1 and number2 together and store the result in a variable called product
let product = number1 * number2;

// Print all results to the console
console.log("Number 1:", number1);
console.log("Number 2:", number2);
console.log("String Number 1:", stringNumber1);
console.log("Sum:", sum);
console.log("Product:", product);
